#!/usr/bin/env bash
# Rebuilds supabase/schema-current.sql: runs every migration in migration-order.txt on an empty test database, exports the result,
# and adds a block that sets permissions exactly as they ended up (so a NEW Supabase project is as locked down as the live one).
# Needs: psql, pg_dump (Postgres 15/16 client tools), python3, and PGHOST / PGUSER / PGPASSWORD for a Postgres you can create databases in.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"; sup="$here/.."
q() { psql -v ON_ERROR_STOP=1 -q "$@"; }
export PGOPTIONS="${PGOPTIONS:--c client_min_messages=warning}"
q -d postgres -c "drop database if exists swaasa_chain" -c "create database swaasa_chain"
q -d swaasa_chain -f "$here/stubs.sql"
while IFS= read -r f; do [[ -z "$f" || "$f" == \#* ]] && continue; q -d swaasa_chain -f "$sup/$f" >/dev/null || { echo "FAILED while applying $f"; exit 1; }; done < "$sup/migration-order.txt"
pg_dump -d swaasa_chain -n public --schema-only --no-owner --no-comments --no-privileges > /tmp/swaasa_dump.sql
psql -d swaasa_chain -Atq > /tmp/swaasa_acl.sql <<'SQL'
select 'revoke all on all tables in schema public from anon, authenticated;';
select 'revoke all on all sequences in schema public from anon, authenticated;';
select 'revoke all on all functions in schema public from public, anon, authenticated;';
select format('grant %s on table public.%I to %s;', string_agg(a.privilege_type, ', ' order by a.privilege_type), c.relname, r.rolname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace, aclexplode(c.relacl) a join pg_roles r on r.oid = a.grantee
 where n.nspname = 'public' and c.relkind in ('r', 'v') and r.rolname in ('anon', 'authenticated') group by c.relname, r.rolname order by c.relname, r.rolname;
select format('grant %s on sequence public.%I to %s;', string_agg(a.privilege_type, ', ' order by a.privilege_type), c.relname, r.rolname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace, aclexplode(c.relacl) a join pg_roles r on r.oid = a.grantee
 where n.nspname = 'public' and c.relkind = 'S' and r.rolname in ('anon', 'authenticated') group by c.relname, r.rolname order by c.relname, r.rolname;
select format('grant execute on function %s to %s;', p.oid::regprocedure, r.rolname)
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace, aclexplode(p.proacl) a join pg_roles r on r.oid = a.grantee
 where n.nspname = 'public' and a.privilege_type = 'EXECUTE' and r.rolname in ('anon', 'authenticated') order by 1;
SQL
python3 - "$sup/schema-current.sql" <<'PY'
import re, sys
out = sys.argv[1]
d = open('/tmp/swaasa_dump.sql', encoding='utf-8').read()
d = re.sub(r'(?m)^\\.*\n', '', d)                                   # psql-only lines the Supabase SQL editor does not accept
d = re.sub(r'(?m)^SELECT pg_catalog.set_config.*\n', '', d)
d = re.sub(r'(?m)^SET (?!check_function_bodies).*\n', '', d)
parts = re.split(r'(?m)^--\n(?=-- Name: )', d); blocks = parts[1:]
typ = lambda b: (re.search(r'-- Name: [^;]*; Type: ([^;]+);', b) or [None, 'OTHER'])[1].strip()
tables = set(re.findall(r'CREATE TABLE public\.(\w+)', d))
sig = lambda b: (re.search(r'CREATE FUNCTION(.*?)(?:LANGUAGE|AS \$)', b, re.S) or [None, ''])[1]
needs_tables = lambda b: any(re.search(r'public\.' + t + r'\b(?!\()', sig(b)) for t in tables)
def pri(b):
    t = typ(b)
    if t in ('TYPE', 'DOMAIN'): return 0
    if t == 'FUNCTION': return 3 if needs_tables(b) else 1       # functions first, except those that take a table's row type
    if t in ('TABLE', 'SEQUENCE'): return 2
    if t == 'VIEW': return 4
    return 5
order = sorted(range(len(blocks)), key=lambda i: (pri(blocks[i]), i))
body = ''.join('--\n' + blocks[i] for i in order).replace('CREATE SCHEMA public;', '-- (the public schema already exists in Supabase)')
body = re.sub(r'\n{3,}', '\n\n', body)
order_files = [l.strip() for l in open(sys.argv[1].replace('schema-current.sql', 'migration-order.txt')) if l.strip() and not l.startswith('#')]
last = order_files[-1]
hdr = f"""-- Swaasa: CURRENT DATABASE SCHEMA. Generated by supabase/tests/regenerate-schema.sh; do not edit by hand.
-- It is the finished database after schema.sql and every migration up to {last}, produced by applying them in order to a test database and exporting the result.
-- Use it for a NEW project (a staging copy, or a rebuild): paste it into the Supabase SQL editor and run it once, then the SEED section at the end.
-- An EXISTING live database must NOT run this file; it only needs the newest migrations it has not had yet (see README-migrations.md).
-- The lock-downs (v22, v25b, v26b) are already included, so a new project starts locked down.

"""
seed = """

-- ───────────── PERMISSIONS ─────────────
-- Supabase gives signed-out and signed-in users wide rights on every new table and function. This block takes them back and grants
-- exactly what the live database allows (the table and function rules are the same ones the lock-down migrations set).
""" + open('/tmp/swaasa_acl.sql', encoding='utf-8').read() + """

-- ───────────── SEED (new project only) ─────────────
insert into public.settings default values on conflict do nothing;
insert into storage.buckets(id, name, public) values ('dress-images', 'dress-images', true) on conflict do nothing;
insert into storage.buckets(id, name, public) values ('return-inspection-photos', 'return-inspection-photos', false) on conflict do nothing;
-- Create the owner: sign up under Supabase > Authentication, then run
--   insert into public.staff(user_id, name, role) values ('<the new user id>', 'Owner name', 'owner');
-- The storage (photo) access rules live in the storage schema, which this export does not cover. Apply the "storage.objects" policies from
-- schema.sql (dress-images) and migration-v10.sql / migration-v20-controls.sql (return-inspection-photos).
"""
open(out, 'w', encoding='utf-8').write(hdr + 'SET check_function_bodies = false;\n\n' + body + seed)
PY
echo "wrote $sup/schema-current.sql"
